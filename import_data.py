    cur = conn.cursor()

    try:
        # 省份
        print(f"[2/5] 导入省份: {len(provinces)} 个")
        execute_values(cur,
            "INSERT INTO t_province (province_code, province_name, center_lon, center_lat) "
            "VALUES %s ON CONFLICT (province_code) DO NOTHING",
            provinces)

        # 城市
        print(f"[3/5] 导入城市: {len(cities)} 个")
        execute_values(cur,
            "INSERT INTO t_city (city_code, city_name, province_name, lon, lat) "
            "VALUES %s ON CONFLICT (city_code) DO NOTHING",
            cities)
        # 更新 geom_point
        cur.execute(
            "UPDATE t_city SET geom_point = ST_SetSRID(ST_MakePoint(lon, lat), 4326) "
            "WHERE lon IS NOT NULL AND lat IS NOT NULL AND geom_point IS NULL"
        )

        # 月度房价
        print(f"[4/5] 导入月度房价: {len(monthly_rows)} 条 (批量写入中...)")
        monthly_data = [(r[0], r[3], r[4], r[5]) for r in monthly_rows]
        batch = 5000
        for i in range(0, len(monthly_data), batch):
            execute_values(cur,
                "INSERT INTO t_monthly_price (city_code, year, month, price) "
                "VALUES %s ON CONFLICT (city_code, year, month) DO NOTHING",
                monthly_data[i:i+batch])
            if (i // batch) % 2 == 0:
                print(f"   已写入 {min(i+batch, len(monthly_data))}/{len(monthly_data)}")

        # 年度房价
        print(f"[5/5] 导入年度房价: {len(yearly_rows)} 条")
        yearly_data = [(r[0], r[3], r[4], r[5], r[6]) for r in yearly_rows]
        execute_values(cur,
            "INSERT INTO t_yearly_price (city_code, year, avg_price, median_price, year_end_price) "
            "VALUES %s ON CONFLICT (city_code, year) DO NOTHING",
            yearly_data)

        conn.commit()
        print("\n===== 导入完成 =====")

        # 统计验证
        cur.execute("SELECT COUNT(*) FROM t_province")
        print(f"  t_province:      {cur.fetchone()[0]} 条")
        cur.execute("SELECT COUNT(*) FROM t_city")
        print(f"  t_city:          {cur.fetchone()[0]} 条")
        cur.execute("SELECT COUNT(*) FROM t_city WHERE lon IS NOT NULL")
        print(f"  t_city(有坐标):  {cur.fetchone()[0]} 条")
        cur.execute("SELECT COUNT(*) FROM t_monthly_price")
        print(f"  t_monthly_price: {cur.fetchone()[0]} 条")
        cur.execute("SELECT COUNT(*) FROM t_yearly_price")
        print(f"  t_yearly_price:  {cur.fetchone()[0]} 条")

    except Exception as e:
        conn.rollback()
        print(f"\n导入失败: {e}")
        sys.exit(1)
    finally:
        cur.close()
        conn.close()


