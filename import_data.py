def get_conn():
    return psycopg2.connect(**DB_CONFIG)


def read_excel():
    print(f"[1/5] 读取 Excel: {EXCEL_PATH}")
    wb = openpyxl.load_workbook(EXCEL_PATH, read_only=True)

    # 月度房价
    ws1 = wb["月度房价"]
    monthly_rows = []
    for i, row in enumerate(ws1.iter_rows(min_row=2, values_only=True)):
        code, city, province, year, month, price = row[0], row[1], row[2], row[3], row[4], row[5]
        if code is not None:
            monthly_rows.append((str(code).zfill(6), city, province, int(year), int(month), price))
    print(f"   月度数据: {len(monthly_rows)} 条")

    # 年度房价
    ws2 = wb["年度房价"]
    yearly_rows = []
    for row in ws2.iter_rows(min_row=2, values_only=True):
        code, city, province, year, avg_p, med_p, end_p = row[0], row[1], row[2], row[3], row[4], row[5], row[6]
        if code is not None:
            yearly_rows.append((str(code).zfill(6), city, province, int(year), avg_p, med_p, end_p))
    print(f"   年度数据: {len(yearly_rows)} 条")

    wb.close()
    return monthly_rows, yearly_rows


def extract_cities(monthly_rows):
    """从月度数据提取唯一城市列表"""
    city_map = {}
    for code, city, province, *_ in monthly_rows:
        if code not in city_map:
            coord = CITY_COORDS.get(city)
            if not coord:
                coord = PROVINCE_COORDS.get(province)
            lon = coord[0] if coord else None
            lat = coord[1] if coord else None
            city_map[code] = (code, city, province, lon, lat)
    return list(city_map.values())


def extract_provinces(monthly_rows):
    """从月度数据提取唯一省份列表"""
    prov_map = {}
    for code, city, province, *_ in monthly_rows:
        prov_code = code[:2] + "0000"
        if province not in prov_map:
            coord = PROVINCE_COORDS.get(province)
            lon = coord[0] if coord else None
            lat = coord[1] if coord else None
            prov_map[province] = (prov_code, province, lon, lat)
    return list(prov_map.values())


